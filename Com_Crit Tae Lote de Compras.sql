SELECT X.SEQGERCOMPRA,
       111 CODIGOCONSIST,
       'Existem ('||COUNT(1)||') acordos não assinados para o representante '||INITCAP(F.NOMERAZAO)||' !' DESCRICAO,
       LISTAGG('Aco.: '||T.NRO_ACORDO||' (Emi.: '||TO_CHAR(T.DATA_EMISSAO, 'DD/MM/YYYY')||')', ', ')
           WITHIN GROUP (ORDER BY T.NRO_ACORDO) COMPLEMENTO,
       'B' BLOQUEIOLIBERACAO
  FROM MAC_GERCOMPRA X INNER JOIN ESP_MAC_GERCOMPRACOMPL C ON X.SEQGERCOMPRA = C.SEQGERCOMPRA
                       INNER JOIN MAF_FORNECCONTATO F ON F.SEQFORNECCONTATO = C.SEQFORNECCONTATO
                       INNER JOIN MAC_GERCOMPRAFORN FO ON FO.SEQGERCOMPRA = X.SEQGERCOMPRA
                       INNER JOIN MAX_COMPRADOR MC ON MC.SEQCOMPRADOR = X.SEQCOMPRADOR
                       INNER JOIN GE_PESSOA G ON G.SEQPESSOA = FO.SEQFORNECEDOR
                       INNER JOIN NAGV_TAE_ACORDOS_V4 T ON T.COD_COMPRADOR = X.SEQCOMPRADOR
                                                        AND T.EMAIL LIKE '%'||F.EMAILACORDO||'%'
 WHERE X.TIPOLOTE = 'C'
   AND X.SITUACAOLOTE NOT IN ('F','C')
   AND X.DTAHORINCLUSAO >= SYSDATE - 30
   AND UPPER(T.STATUS) LIKE '%AGUARD%'
   AND T.DATA_EMISSAO <= SYSDATE - 30
   -- validar se permite liberar pela view
   /*AND NOT EXISTS (SELECT 1
                     FROM NAGT_LOTE_LIBERADO_CRIT L
                    WHERE L.SEQGERCOMPRA = X.SEQGERCOMPRA)*/
   AND 1=1
 GROUP BY X.SEQGERCOMPRA, F.NOMERAZAO;
